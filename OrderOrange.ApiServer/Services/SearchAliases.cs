    /// <summary>Brand aliases that are ordinary English words — they stay searchable,
    /// but must never attach keywords to unrelated products ("Rainbow Roll" ≠ milk).</summary>
    private static readonly HashSet<string> AmbiguousAliases =
        ["rainbow", "clear", "original", "galaxy", "mars", "bounty", "anchor", "dove", "crest", "oasis", "fine", "beats", "honor", "plates", "plate", "bag", "bags", "case", "mask", "top"];

    /// <summary>Every word in the dictionary — typo correction must know all of them
    /// even when no product currently carries the keyword.</summary>
    public static readonly IReadOnlySet<string> DictionaryWords = BuildDictionaryWords();

    private static HashSet<string> BuildDictionaryWords()
    {
        var words = new HashSet<string>();
        foreach (var (english, aliases) in Map)
            foreach (var text in aliases.Prepend(english))
                foreach (var token in SmartSearch.Tokens(text))
                    if (token.Length >= 3)
                        words.Add(token);
        return words;
    }

    /// <summary>
    /// All dictionary keywords for one product, drawn from every text that describes it
    /// (name, category, cuisine). Stored in the SearchKeywords column so search hits
    /// keywords, not just titles. "Water 12x500ml" → "water ماء مياه ما موية آب پانی…".
    /// </summary>
    public static string KeywordsFor(params string?[] texts)
    {
        var text = string.Join(' ', texts.Where(t => !string.IsNullOrWhiteSpace(t)));
        var norm = SmartSearch.Normalize(text);
        // Whole words only (plural-folded): "cola" must not fire inside "Rucola".
        var tokens = SmartSearch.Tokens(text).Select(t => t.TrimEnd('s')).ToHashSet();

        var parts = new List<string>();
        foreach (var (english, aliases) in Map)
        {
            // The entry applies when the product carries the canonical word OR any of
            // its aliases — "Tide Powder" must inherit the detergent keywords via "tide".
            var hit = english.Contains(' ')
                ? norm.Contains(english, StringComparison.OrdinalIgnoreCase)
                : tokens.Contains(english.TrimEnd('s'));
            if (!hit)
            {
                foreach (var alias in aliases)
                {
                    var a = SmartSearch.Normalize(alias).Trim();
                    if (a.Length < 3 || AmbiguousAliases.Contains(a)) continue;
                    hit = a.Contains(' ') ? norm.Contains(a) : tokens.Contains(a.TrimEnd('s'));
                    if (hit) break;
                }
            }
            if (!hit) continue;
            parts.Add(english);
            parts.AddRange(aliases);
        }
        var joined = string.Join(' ', parts.Distinct());
        return joined.Length > 1900 ? joined[..1900] : joined;
    }

    /// <summary>
    /// Which dictionary words the user typed in THEIR language: canonical English →
    /// the alias found inside the query ("پیتزا" ⇒ { pizza → پیتزا }). Lets search
    /// results echo the query's own language, whatever the app language is.
    /// </summary>
    public static Dictionary<string, string> MatchedAliases(string query)
    {
        var norm = SmartSearch.Normalize(query);
        var tokens = norm.Split(' ', StringSplitOptions.RemoveEmptyEntries).ToHashSet();
        var map = new Dictionary<string, string>();
        foreach (var (english, aliases) in Map)
        {
            if (norm.Contains(english, StringComparison.OrdinalIgnoreCase)) continue; // typed in English already
            foreach (var alias in aliases)
            {
                var a = SmartSearch.Normalize(alias).Trim();
                if (a.Length == 0) continue;
                var hit = a.Length <= 3 && !a.Contains(' ') ? tokens.Contains(a) : norm.Contains(a);
                if (hit)
                {
                    map[english] = alias.Trim();
                    break;
                }
            }
        }
        return map;
    }

    /// <summary>
    /// Rewrites a result name into the query's language: recognized English words are
    /// replaced by the alias the user typed ("Masafi Water 6x500ml" + آب ⇒ "Masafi آب
    /// 6x500ml"). When nothing is replaceable but the product carries the concept in
    /// its keywords, the typed word is appended as a tag ("Margherita · پیتزا").
    /// </summary>
    public static string LocalizeName(string name, Dictionary<string, string> matched, string? keywords = null)
    {
        if (matched.Count == 0) return name;
        var result = name;
        var replaced = false;
        foreach (var (english, alias) in matched)
        {
            var idx = result.IndexOf(english, StringComparison.OrdinalIgnoreCase);
            while (idx >= 0)
            {
                var startOk = idx == 0 || !char.IsLetter(result[idx - 1]);
                var endAt = idx + english.Length;
                // swallow a plural 's' so "Wings" becomes the alias cleanly
                if (endAt < result.Length && (result[endAt] == 's' || result[endAt] == 'S')) endAt++;
                var endOk = endAt >= result.Length || !char.IsLetter(result[endAt]);
                if (startOk && endOk)
                {
                    result = result[..idx] + alias + result[endAt..];
                    replaced = true;
                    idx = result.IndexOf(english, Math.Min(idx + alias.Length, result.Length), StringComparison.OrdinalIgnoreCase);
                }
                else
                {
                    idx = result.IndexOf(english, idx + 1, StringComparison.OrdinalIgnoreCase);
                }
            }
        }
        if (!replaced && keywords is not null)
        {
            foreach (var (english, alias) in matched)
            {
                if (keywords.Contains(english, StringComparison.OrdinalIgnoreCase))
                {
                    result = $"{name} · {alias}";
                    break;
                }
            }
        }
        return result;
    }

    /// <summary>
    /// Expands a raw query into the terms worth matching: the query itself plus any
    /// English catalog keywords whose foreign aliases appear inside it. Short aliases
    /// (≤3 letters, e.g. "ما", "آب", "su") must match a whole word so they don't fire
    /// inside unrelated words; longer ones match as substrings. Everything is compared
    /// through the same normalizer as the search engine (diacritics, letter forms).
    /// </summary>
    public static List<string> Expand(string query)
    {
        var terms = new List<string> { query };
        var norm = SmartSearch.Normalize(query);
        var tokens = norm.Split(' ', StringSplitOptions.RemoveEmptyEntries).ToHashSet();

        foreach (var (english, aliases) in Map)
        {
            if (norm.Contains(english, StringComparison.OrdinalIgnoreCase)) continue;
            foreach (var alias in aliases)
            {
                var a = SmartSearch.Normalize(alias).Trim();
                if (a.Length == 0) continue;
                var hit = a.Length <= 3 && !a.Contains(' ') ? tokens.Contains(a) : norm.Contains(a);
                if (hit)
                {
                    terms.Add(english);
                    break;
                }
            }
        }
        return terms;
    }
